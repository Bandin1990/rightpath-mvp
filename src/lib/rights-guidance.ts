export function suggestRights(storyText: string, limit = 5): SuggestedRight[] {
  const normalizedText = storyText.toLocaleLowerCase("th-TH");
  const matched = rightRules
    .map((rule) => {
      const matchedKeywords = rule.keywords.filter((keyword) => normalizedText.includes(keyword.toLocaleLowerCase("th-TH")));
      return { rule, matchedKeywords };
    })
    .filter(({ matchedKeywords }) => matchedKeywords.length > 0)
    .sort((left, right) => right.matchedKeywords.length - left.matchedKeywords.length)
    .slice(0, limit)
    .map(({ rule, matchedKeywords }) => ({
      id: rule.id,
      title: rule.title,
      plainLanguage: rule.plainLanguage,
      whyMatched: `${rule.matchReason} เช่น “${matchedKeywords.slice(0, 3).join("”, “")}”`,
      whatToCheck: rule.whatToCheck,
      sources: rule.sources,
      lastVerifiedAt: rule.lastVerifiedAt,
    }));

  return matched.length > 0 ? matched : [fallbackRight];
}
